"""PlatformIO pre-build script: gzip web/index.html into include/web_page_gen.h.

The dashboard is served straight from flash with Content-Encoding: gzip, so
there's no filesystem image to upload - `pio run -t upload` is enough.
"""
import gzip
import os

Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
src = os.path.join(project_dir, "web", "index.html")
dst = os.path.join(project_dir, "include", "web_page_gen.h")

with open(src, "rb") as f:
    html = f.read()
data = gzip.compress(html, compresslevel=9, mtime=0)

lines = []
for i in range(0, len(data), 20):
    lines.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 20]) + ",")

header = (
    "// GENERATED by tools/embed_web.py from web/index.html - do not edit.\n"
    "#pragma once\n"
    "#include <Arduino.h>\n\n"
    "static const size_t WEB_PAGE_GZ_LEN = %d;\n"
    "static const uint8_t WEB_PAGE_GZ[] PROGMEM = {\n%s\n};\n"
) % (len(data), "\n".join(lines))

old = None
if os.path.exists(dst):
    with open(dst, "r") as f:
        old = f.read()
if old != header:
    with open(dst, "w") as f:
        f.write(header)
    print("embed_web: %s -> %s (%d -> %d bytes gzipped)" % (
        os.path.relpath(src, project_dir), os.path.relpath(dst, project_dir), len(html), len(data)))
